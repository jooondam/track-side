async function freePort() {
  return new Promise((res, rej) => {
    const srv = createServer();
    srv.on("error", rej);
    srv.listen(0, "127.0.0.1", () => {
      const { port } = srv.address();
      srv.close(() => res(port));
    });
  });
}

/** start `vite preview` and resolve once it is actually answering. */
async function startServer(port) {
  // `detached` puts npx and everything it spawns in one process group, so `stopServer` can signal
  // the group. Killing the returned handle alone is not enough and quietly does not work: the
  // handle is the *npx wrapper*, which spawns `sh -c vite preview`, which spawns the node process
  // actually holding the port. Killing npx therefore orphans that grandchild, which keeps the
  // inherited stderr pipe open -- and a pipe with a listener on it holds the event loop, so the
  // harness never exited either, on success as much as on failure. The symptom is a run that
  // prints every frame and then hangs forever, with a preview server still on its port.
  const child = spawn(
    "npx",
    ["vite", "preview", "--port", String(port), "--strictPort", "--host", "127.0.0.1"],
    { cwd: ROOT, stdio: ["ignore", "pipe", "pipe"], detached: true },
  );
  child.stderr.on("data", (b) => process.stderr.write(`[vite] ${b}`));

  const base = `http://127.0.0.1:${port}/`;
  const deadline = Date.now() + 30_000;
  for (;;) {
    if (child.exitCode !== null) throw new Error(`vite preview exited with ${child.exitCode}`);
    try {
      const r = await fetch(base);
      if (r.ok) break;
    } catch {
      /* not up yet */
    }
    if (Date.now() > deadline) throw new Error(`vite preview did not answer on ${base}`);
    await new Promise((r) => setTimeout(r, 250));
  }
  return { child, base };
}

/** stop the whole `vite preview` process group started by startServer. */
function stopServer(child) {
  try {
    process.kill(-child.pid, "SIGTERM");
  } catch {
    /* already gone, or never grouped: fall back to the handle itself */
    child.kill();
  }
}

async function capture(page, base, name, query, pins = {}) {
  // seed the panel pins before any script runs, since useExpandable reads them during its first
  // render. Same localStorage keys the pin button writes.
  await page.addInitScript((p) => {
    try {
      localStorage.setItem("track-side:pin:dock", p.dock ? "1" : "0");
      localStorage.setItem("track-side:pin:side", p.side ? "1" : "0");
    } catch {
      /* storage unavailable: the shot is just taken with the panels shut */
    }
  }, pins);

  await page.goto(`${base}?${query}`, { waitUntil: "domcontentloaded" });

  await page.waitForFunction(() => window.__trackSideReady === true, null, {
    timeout: READY_TIMEOUT_MS,
  });

  // the corner report lives behind a tab that has no URL state, because it is a view of the dock
  // rather than a view of the circuit. Clicking it is what a person would do.
  if (pins.tab === "corners") {
    await page.getByRole("button", { name: "corners" }).click();
  }

  // let the GLB, the environment bake and the shader compiles land. Counting real animation
  // frames rather than sleeping means this tracks how slow the software rasteriser actually is
  // on this machine instead of guessing.
  await page.evaluate(
    (frames) =>
      new Promise((done) => {
        let left = frames;
        const tick = () => (left-- > 0 ? requestAnimationFrame(tick) : done());
        requestAnimationFrame(tick);
      }),
    SETTLE_FRAMES + (pins.extraFrames ?? 0),
  );

  const file = resolve(OUT, `${name}.png`);
  await page.screenshot({ path: file });

  // a doc frame is the same frame, written a second time where the README reads it from. Written
  // from the same settled page rather than a second run, so the committed image and the reviewable
  // one cannot disagree about what the viewer did.
  if (pins.doc) {
    const docFile = resolve(ROOT, pins.doc);
    await mkdir(dirname(docFile), { recursive: true });
    await page.screenshot({ path: docFile, type: "jpeg", quality: DOC_QUALITY });
    return `${file}  +  ${pins.doc}`;
  }
  return file;
}

async function main() {
  const filter = process.argv.slice(2).filter((a) => !a.startsWith("-"));
  const wanted = filter.length
    ? SHOTS.filter(([name]) => filter.some((f) => name.includes(f)))
    : SHOTS;
  if (!wanted.length) {
    console.error(`no shots match ${filter.join(", ")}. Known: ${SHOTS.map((s) => s[0]).join(", ")}`);
    process.exitCode = 1;
    return;
  }

  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  const { child, base } = await startServer(await freePort());
  // `channel: "chromium"` is load-bearing, not a preference. Playwright's default headless is the
  // old headless shell, and it composites this canvas wrong: the presented frame drops the top
  // `insets.bottom` rows of the drawing buffer, so with the dock open the upper half of the circuit
  // is missing and the corner labels hang over blank sheet. The WebGL buffer itself is correct
  // there (readPixels on the same frame returns the road at those rows, and a headed browser
  // screenshots it intact), so it is a capture artifact, and every frame this harness produced
  // before this line was lying about the product. The new headless mode composites it correctly.
  // Needs `npx playwright install chromium`.
  //
  // `SHOTS_CHROMIUM` overrides that with a path, for sandboxes that ship a browser Playwright did
  // not download and cannot: the pinned revision is not the installed one, and `channel` resolves
  // by revision. It must point at the **full** chromium binary, not `headless_shell` — the shell
  // is the build with the compositing bug described above, so pointing this at one would quietly
  // reintroduce every problem `channel` was added to fix.
  //
  // Everything from here down runs inside the try, so that the `finally` below is reached however
  // this fails. It was not always: the browser was launched outside it, so a launch that threw --
  // a missing or mismatched chromium, the single most likely failure on a fresh machine -- left
  // `vite preview` running with nothing to stop it. The spawned child keeps the event loop alive,
  // so the script did not exit either. It reported the error and then hung, holding a port, and a
  // second attempt started a second one.
  let browser = null;
  try {
    const exe = process.env.SHOTS_CHROMIUM;
    browser = await chromium.launch(
      exe ? { executablePath: exe } : { channel: "chromium" },
    );

    // surface page errors: a shader that fails to compile renders a black frame and otherwise
    // says nothing at all, which is the single most likely way this script lies to you
    const watch = (p) => {
      p.on("pageerror", (e) => console.error(`  ! page error: ${e.message}`));
      p.on("console", (m) => {
        if (m.type() === "error") console.error(`  ! console: ${m.text()}`);
      });
      return p;
    };

    const page = watch(await browser.newPage({ viewport: VIEWPORT, deviceScaleFactor: 1 }));
    // doc frames get their own page at DOC_SCALE. Same CSS viewport, so the layout under review is
    // the same one; only the pixel density differs, which is what a retina laptop already does.
    // Created lazily, since most runs ask for no doc frame and the software rasteriser makes a
    // second page cost real time.
    let docPage = null;
    const pageFor = async (pins) => {
      if (!pins?.doc) return page;
      docPage ??= watch(
        await browser.newPage({ viewport: VIEWPORT, deviceScaleFactor: DOC_SCALE }),
      );
      return docPage;
    };

    for (const [name, query, pins] of wanted) {
      const t0 = Date.now();
      try {
        const file = await capture(await pageFor(pins), base, name, query, pins);
        console.log(`${name}  ${((Date.now() - t0) / 1000).toFixed(1)}s  ${file}`);
      } catch (err) {
        console.error(`${name}  FAILED: ${err.message}`);
        process.exitCode = 1;
      }
    }
  } finally {
    await browser?.close();
    stopServer(child);
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
