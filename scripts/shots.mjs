// headless screenshots of the viewer, so a visual change can be reviewed without committing,
// pushing, and waiting for Pages.
//
//   npm run shots                  every frame in SHOTS
//   npm run shots -- spa           only frames whose name contains "spa"
//
// It drives the app entirely through the query string (src/ui/urlState.ts), so there is no test
// hook, no injected state and no privileged build: every frame it captures is a URL a person can
// open. That is the point of the URL state, not a side effect of it.
//
// Two things make this slower than it looks and both are unavoidable. Headless Chromium has no
// GPU, so WebGL runs on SwiftShader's software rasteriser; and the scene compiles its shaders on
// first draw, bakes a one-frame <Environment>, and streams the GLB through Suspense. The wait is
// therefore "ready flag, then a fixed number of animation frames", not a networkidle: networkidle
// fires while the terrain is still black.

import { spawn } from "node:child_process";
import { mkdir, rm } from "node:fs/promises";
import { createServer } from "node:net";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "shots");
const VIEWPORT = { width: 1600, height: 900 };
/** animation frames to let pass after the ready flag, before capturing. */
const SETTLE_FRAMES = 90;
/** how long to wait for the ready flag before giving up on a frame. */
const READY_TIMEOUT_MS = 60_000;

// The two frames the README prints are captured here, by the same harness, from the same URLs as
// every other frame: a shot carrying `doc` also writes a committed JPEG to that repo path.
//
// This exists because those two images had drifted off the product and nothing said so. They were
// added in dd2f7f8 on the other side of the split the 2026-08-27 merge reconciled, so they
// photograph a viewer that predates the interface rebuild, self-hosted Archivo and the corner
// re-measurement, and they are both the work-lamp rendition while the default is daylight. Hand
// dropped images cannot go stale loudly. These can: `npm run shots` rewrites them, so a rebuild
// that changes what the viewer looks like leaves the drift sitting in `git status`.
//
// Retina because the README is read on laptop displays and the originals were 2880x1800; JPEG
// because these are photographs of a shaded 3D scene, where PNG costs about four times the bytes
// for nothing a reader can see.
const DOC_SCALE = 2;
const DOC_QUALITY = 82;

// [name, query, pins?]. Names are filenames, so keep them filesystem-safe.
//
// `pins` opens the rail and the dock. Those are hover-to-peek panels whose pinned state lives in
// localStorage (src/ui/useExpandable.ts), not in the URL, so a headless run with no pointer would
// otherwise only ever photograph them shut. Seeding the same key the app reads is honest: it is
// the state a user gets by clicking the pin, not a special mode.
//
// `doc` is a repo-relative path the frame is additionally written to, as a retina JPEG. Only the
// README's frames carry it, and they are their own entries rather than a flag on a review frame:
// a doc frame carries two query parameters the review frames deliberately do not.
//
// A committed image regenerated by a routine command has to be reproducible or the property it was
// wired for is worthless: if every run rewrites ~700 kB of JPEG, real drift is indistinguishable
// from the churn. Both halves of that are needed and `play=0` alone is not enough, which is worth
// knowing before someone drops one of them:
//
//   play=0    freezes the lap clock. Otherwise the car and the telemetry readout sit wherever the
//             clock reached during the settle, and each run photographs a different moment.
//   motion=0  stops the scene animation. It defaults to the OS's prefers-reduced-motion, which in
//             a headless browser means motion *on*, so the terrain kept shimmering under a frozen
//             car and the bytes still moved.
//
// With both, two runs in separate browsers produce byte-identical files -- measured, not assumed --
// so a diff here means the viewer changed.
//
// `furniture=0` is the third, and it is a choice about the pictures rather than about determinism:
// the poles, gantries and boards stand between the camera and the road in every frame that has
// them, and the README is selling the line and the terrain. The braking boards are the one real
// loss, and the braking report is where those are actually read anyway.
//
// The rail and the dock are the instrument panel, and a screenshot with them shut is a picture of
// a 3D scene rather than of this tool, so one frame pins them open. Only one, and not the one that
// would show them best: **with both pinned, a `corner:` viewpoint draws no road at all**, and the
// fitted overview clips the top of the circuit. Both reproduce at deviceScaleFactor 1, so this is
// the product and not the capture. verify-p0.mjs pins both panels for the desktop, plan and chase
// frames but never for a corner, which is why it has never been photographed. Until that is fixed
// the chase frame carries the panels, because it is the one that survives them.
